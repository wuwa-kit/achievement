import { expect, test } from '@playwright/test'
import { selectValue } from './select-helpers'
for (const route of ['/', '/desktop']) {
  test(`theme modes follow system and persist on ${route}`, async ({ page, context }, testInfo) => {
    await page.emulateMedia({ colorScheme: 'dark' })
    await page.goto(route)
    await expect(page.locator(route === '/' ? '.workspace' : '.desktop-page')).toBeVisible()
    const root = page.locator('html')
    const trigger = page.getByTestId('theme-switch')
    await expect(root).toHaveAttribute('data-theme-mode', 'auto')
    await expect(root).toHaveAttribute('data-theme', 'dark')
    await expect(trigger).toBeVisible()
    await trigger.click()
    await expect(page.locator('.w-select-option')).toHaveCount(3)
    await expect(page.locator('.w-select-popover')).toHaveCSS('opacity', '1')
    await page.screenshot({ path: testInfo.outputPath('dark.png') })
    await trigger.press('Escape')
    await page.emulateMedia({ colorScheme: 'light' })
    await expect(root).toHaveAttribute('data-theme', 'light')
    await selectValue(page, trigger, 'dark')
    await page.reload()
    await expect(root).toHaveAttribute('data-theme-mode', 'dark')
    await expect(root).toHaveCSS('color-scheme', 'dark')
    await selectValue(page, trigger, 'light')
    await page.emulateMedia({ colorScheme: 'dark' })
    await expect(root).toHaveAttribute('data-theme', 'light')
    const other = await context.newPage()
    await other.goto(route)
    await expect(other.locator('html')).toHaveAttribute('data-theme-mode', 'light')
    await selectValue(page, trigger, 'auto')
    await expect(root).toHaveAttribute('data-theme', 'dark')
    await expect(other.locator('html')).toHaveAttribute('data-theme-mode', 'auto')
    await other.close()
  })
}
