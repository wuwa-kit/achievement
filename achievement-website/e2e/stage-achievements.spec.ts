import { expect, test } from '@playwright/test'

test('stage edits cascade from list and detail, retain new completions and persist together', async ({
  page,
}) => {
  await page.goto('/')
  await page.getByTestId('搜索成就').fill('100403')
  const group = page.getByTestId('stage-achievements-100402')
  const rows = group.locator('.achievement-row')
  const hideCompleted = page.getByTestId('隐藏已完成')
  const reward = page.getByTestId('completed-astrite')
  const expectStates = async (states: boolean[]) => {
    await expect(rows).toHaveCount(3)
    for (const [index, completed] of states.entries())
      await expect(rows.nth(index)).toHaveAttribute('data-completed', completed.toString())
  }

  await hideCompleted.check()
  await expect(group.locator(':scope > div').first()).toHaveText('阶段成就')
  await expectStates([false, false, false])
  for (let index = 0; index < 3; index++) await expect(rows.nth(index)).toBeEnabled()
  await expect(group.locator('[data-waiting]')).toHaveCount(0)
  await rows.nth(1).press('Enter')
  await expectStates([true, true, false])
  await expect(reward).toHaveText('15')

  await group.getByTestId('查看成就详情 100411').click()
  const edit = page.getByTestId('编辑成就完成状态')
  await expect(edit).toBeEnabled()
  await edit.check()
  await expectStates([true, true, true])
  await expect(reward).toHaveText('35')
  await page.getByTestId('关闭详情').click()
  await group.getByTestId('查看成就详情 100403').click()
  await edit.uncheck()
  await expectStates([true, false, false])
  await expect(reward).toHaveText('5')
  await page.getByTestId('关闭详情').click()
  await rows.nth(0).press('Enter')
  await expectStates([false, false, false])
  await expect(reward).toHaveText('0')

  await rows.nth(2).press('Enter')
  await expectStates([true, true, true])
  await expect(reward).toHaveText('35')
  await group.getByTestId('查看成就详情 100403').click()
  await expect(edit).toBeChecked()
  await page.getByTestId('关闭详情').click()
  await page.reload()
  await expect(hideCompleted).toBeChecked()
  await expect(page.getByTestId('成就列表')).toHaveAttribute('data-count', '0')
  await hideCompleted.uncheck()
  await expectStates([true, true, true])
  await rows.nth(1).press('Enter')
  await expectStates([true, false, false])
  await expect(reward).toHaveText('5')
  await group.getByTestId('查看成就详情 100403').click()
  await expect(edit).not.toBeChecked()
  await page.getByTestId('关闭详情').click()
  await page.reload()
  await expectStates([true, false, false])
  await expect(reward).toHaveText('5')
})
